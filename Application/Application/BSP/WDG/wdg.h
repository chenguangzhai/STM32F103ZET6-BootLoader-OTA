/**
 * 独立看门狗（IWDG）封装。
 *
 * 为什么这个项目需要它 —— 它不是"保险"而是"回滚机制能成立的前提"。
 *
 * 没有狗的时候，一个"初始化全过、进主循环就死在某处"的固件是这样的：
 *   跳转过去 → 打印完 starting → 卡死 → 板子安静地挂在那儿，永不复位
 *   → 试用计数永远停在 0/3 → 既不转正也不回滚 → 用户只能拆机接 ST-Link
 * 有了狗，同一个固件：
 *   卡死 → 2 秒后自动复位 → Boot 发现 TRIAL 未确认 → 计 1 次 → …
 *   → 第 3 次用完 → 自动把槽 B 的旧版搬回来 → 板子自己好了
 *
 * 只在 App 里开狗，BootLoader 不开。原因：软件狗（option byte 保持默认
 * WDG_SW=1）在系统复位后就处于关闭状态，必须由软件写 0xCCCC 才启动。
 * 所以 App 里 NVIC_SystemReset 回 Boot 之后狗已经停了，Boot 搬运 8 秒
 * 那种长阻塞不会被它打断，Boot 侧一行代码都不用改。
 *
 * 反过来，如果哪天有人把 option byte 改成硬件看门狗，这个假设立刻失效，
 * Boot 会在大固件搬运到一半时被复位。真要那么改，必须给 Boot 也补喂狗。
 */
#ifndef __WDG_H
#define __WDG_H

#include <stdint.h>

/* 超时 2 秒。定这个值的依据：
 *   1) 要比主循环里最长的一次阻塞大一个数量级。当前最长的是 W25Q 单扇区
 *      擦除 45ms（OTA 接收时每 2KB 触发一次），2s / 45ms ≈ 44 倍余量。
 *   2) 要短到"死机后用户还没来得及怀疑板子坏了"就能自愈。
 *   3) LSI 实际频率 30~60kHz（数据手册），2.0s 标称对应实测 1.33~2.67s，
 *      两端都还在可接受范围内。 */
#define WDG_TIMEOUT_MS      2000U

/**
 * 启动看门狗。
 *
 * 必须在所有"可能耗时"的初始化之后调用 —— 狗一开就开始倒计时，
 * 而调用它的那一刻到进主循环之间不允许有超过 WDG_TIMEOUT_MS 的操作。
 *
 * 一旦启动就无法关闭（硬件特性，不是没写 stop 函数）。
 */
void Wdg_Init(void);

/**
 * 喂狗。必须在主循环里调，且只在这一处调。
 *
 * 为什么强调"只在主循环"：如果把它挪进某个定时器中断，那么即使主循环
 * 已经死循环，中断照样按点喂狗，狗就变成了一个纯粹的装饰 —— 这是嵌入式
 * 里最常见也最难查的看门狗失效方式。
 */
void Wdg_Feed(void);

/** 狗是否已经启动（1=已启动）。用于避免未初始化就 Refresh 触发 HardFault */
uint8_t Wdg_IsRunning(void);

#endif
