/**
 * App 侧固件接收器：一直监听串口，收到就写进 W25Q 的槽 A
 *
 * ================== 为什么由 App 收，而不是 Boot ==================
 *
 * Boot 收固件的模式是"上电后抢一个 3 秒窗口"，过了窗口就跳走。
 * 这个模式有三个绕不过去的毛病：
 *   1) 现场没有电脑连着串口时，永远升不了级
 *   2) 收错了没法重来 —— 上电那一刻就已经把旧固件擦了
 *   3) 升级时机被板子的上电时刻决定，而不是被用户决定
 *
 * 交给 App 收之后，下载全程不碰内部 Flash：旧固件一直是完好的，
 * 用户可以随时反悔、断网、走人。真正动内部 Flash 的只有"搬运"那一下，
 * 而搬运发生在 Boot 里，条件是新固件已经完整躺在槽 A 且 CRC 对得上。
 *
 * ================== 为什么"一直监听"不会误触发 ==================
 *
 * 串口上同时跑着业务数据（USART1 就是 Modbus 口）。要避免把业务字节
 * 当成固件，靠两层过滤：
 *   第一层：4 字节 'FWUP' 标识。业务数据里连续出现这 4 个字节的概率是 2^-32
 *   第二层：头部自带 28 字节的 CRC32。两层的误判是独立的，叠起来可以不管
 *
 * ================== 状态机 ==================
 *
 *   IDLE    ──扫到 'F','W','U','P'──►  HEADER
 *   HEADER  ──收满 32 字节且校验通过──►  DATA
 *   DATA    ──收满 fw_len 字节────────►  校验 CRC → 写头 → 软复位
 *
 * 任何一步失败都退回 IDLE，且**不写头部**。因为"头部存在"等价于
 * "固件完整且校验过"，所以中途失败不会留下一个骗人的有效槽。
 */

#ifndef __APP_OTA_H
#define __APP_OTA_H

#include <stdint.h>

/* 初始化接收状态机。上电调一次即可 */
void AppOta_Init(void);

/* 告诉 Boot「这一版我已经跑起来了」（阶段 4 的试用确认）。
 *
 * 调用时机：初始化完成、确定自己没死掉之后，调一次。
 * 放在 init 结尾就够 —— 真正的目的是区分"固件能跑完初始化"和
 * "一上电就 HardFault"，不需要等到主循环跑稳。
 *
 * 返回 1 = 确认标记已就位（或本来就在），0 = 没有参数页 / 写失败。
 * 内部只写 W25Q 的一个标记扇区，不碰内部 Flash。
 * 已经确认过就不重复写，免得每次上电都擦一次。 */
uint8_t AppOta_Confirm(void);

/* 非阻塞轮询，必须在主循环里反复调用。
 * 内部只做"取一次串口缓冲 → 喂进状态机"，不会阻塞等数据，
 * 所以主循环里的其他事情（闪灯、业务）不会被拖慢 */
void AppOta_Poll(void);

#endif /* __APP_OTA_H */
