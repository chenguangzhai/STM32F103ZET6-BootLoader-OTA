/**
 * 槽 → 内部 Flash 的搬运（阶段 3）
 *
 * 位置在整条升级链的最后一环：
 *   App 收固件 → 写 W25Q 槽 A → 写头部 → 软复位
 *   → **Boot 上电读槽头 → 认为该装 → 搬进内部 Flash → 校验 → 改参数 → 跳转**
 *
 * 为什么搬运这个动作必须放在 Boot 里：
 *   内部 Flash 的擦写会让 CPU 暂停取指（F103 单 bank），而且一旦擦掉
 *   正在执行的 App，代码本身也没了。所以只能由一个"不在 App 区"的程序来做。
 *
 * 失败语义（重要，别改错）：
 *   搬运过程中旧 App 已经被擦掉了，此刻断电 = 内部 Flash 里是残缺固件。
 *   但因为**参数页要等校验通过之后才更新**，Boot 下次上电会发现
 *   "参数里记的 CRC 对不上" → 不跳转 → 停在串口等重传。
 *   也就是说：最坏结果是"变砖需重刷"，不会"跳进半截固件跑飞"。
 */
#ifndef __OTA_APPLY_H
#define __OTA_APPLY_H

#include <stdint.h>

/* ==================== 返回值 ==================== */
#define OTA_APPLY_OK        0       /* 搬运完成，内部 Flash 里已是这份固件 */
#define OTA_APPLY_ALREADY   1       /* 内部 Flash 本来就已经是这份固件，只补了标记 */
#define OTA_APPLY_NOOP      2       /* 没有待装的固件（空槽 / 已搬过 / 头不可信） */
#define OTA_APPLY_REJECT    3       /* 头合法但不能装（自测假头、超出 App 区、降级） */
#define OTA_APPLY_ERR      (-1)     /* 搬运失败，槽头已作废（避免每次上电重试） */

/**
 * 是否允许把比当前更旧的固件刷进来。0 = 拒绝（默认），1 = 放行。
 *
 * 为什么需要这一条：CRC 不能当身份用 —— 同一份源码重编一次，__DATE__/__TIME__
 * 变了 CRC 就变，Boot 无法从中分辨"只是重编"和"这是另一个固件"。版本号是
 * 唯一能表达新旧关系的字段，不比较它就等于任何版本都能覆盖任何版本。
 *
 * 为什么做成编译期开关而不是界面上一个勾选：这个判断的全部意义就是挡误操作，
 * 而"界面上多一个可以点的强制按钮"让误点的概率比误发旧固件还高。
 * 真要降级有两条正路：改这里的宏重编 Boot，或者走槽 B 回滚
 * （OtaApply_RestoreFromB 不受这条限制，它本来就是降级动作）。
 */
#ifndef OTA_ALLOW_DOWNGRADE
#define OTA_ALLOW_DOWNGRADE     0
#endif

/**
 * 把指定槽里"待装"的固件搬进内部 App 区。
 *
 * 会做的事，按顺序：
 *   1. 读槽头；非 OK、已带 COPIED、带 SELFTEST → 直接返回，不动内部 Flash
 *   2. 长度超过 OTA_APP_MAX（会压到参数页）→ 拒绝
 *   3. 若内部 Flash 现有内容 CRC 已经等于槽头记的 CRC → 不重复擦写，只补 COPIED
 *   4. 逐页搬：读 W25Q 2KB → 擦内部一页 → 写进去
 *   5. 整个 App 区读回来重算 CRC，和槽头比对（不合格就不动参数页）
 *   6. 先写参数页，再给槽头打 COPIED —— 顺序不能反，理由见 .c
 */
int8_t OtaApply_FromSlot(uint8_t slot);

/**
 * 从槽 B 回滚到内部 Flash（阶段 4）。
 *
 * 调用时机只有一个：新固件试用次数用完了，还没被 App 确认过 ——
 * 也就是"装上之后每次上电都没跑起来"。
 *
 * 会做的事：
 *   1. 读槽 B 头；非 OK / 自测假头 / 长度越界 → 拒绝，什么都不动
 *   2. 逐页搬回内部 Flash
 *   3. 回读 CRC 校验，不过就返回错误（此时内部 Flash 已残缺，但参数页还没改，
 *      Boot 仍不会跳转，停在串口等重传）
 *   4. 参数页写成"已确认"，避免下次上电又判成试用中、来回滚
 *   5. 擦掉槽 A 的头部（那份固件已证明跑不起来）
 */
int8_t OtaApply_RestoreFromB(void);

/**
 * 参数页丢失后的自愈（账本重建）。
 *
 * 参数页只是"记账本"，真相在别处且有两份：W25Q 槽头里的 len/crc，以及
 * 内部 Flash 里那段字节本身。所以账本被擦掉（IDE 全片下载、批量烧片、
 * 任何一次整片擦除）之后，不该连试用计数和回滚能力一起失效 ——
 * 重新对一次账就能恢复。
 *
 * 只在参数页**整页空白**时动手。有内容却校验不过属于"写到一半断电"，
 * 那种情况不能猜，留给 CheckAppBoot 报损坏并停在 OTA。
 *
 * 重建一律写成"试用中、计数 0"，绝不直接写已确认：此刻只能证明
 * "内部 Flash 和槽里那份一模一样"，证明不了它跑得起来。
 * 代价极小 —— App 正常启动 5 秒后自确认；真是坏固件三次后照样回滚。
 *
 * 返回：OTA_APPLY_OK 重建成功 / OTA_APPLY_NOOP 无需重建 /
 *       OTA_APPLY_ERR 对不上任何槽或写入失败
 */
int8_t OtaApply_RecoverParam(void);

#endif
